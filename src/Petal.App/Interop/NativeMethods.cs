    public static void InjectZeroMouseMove()
    {
        var input = new INPUT { type = INPUT_MOUSE, u = new INPUTUNION { mi = new MOUSEINPUT { dwFlags = MOUSEEVENTF_MOVE } } };
        SendInput(1, [input], Marshal.SizeOf<INPUT>());
    }

    public static (RECT Monitor, RECT Work, double Scale) MonitorAt(POINT pt)
    {
        var mon = MonitorFromPoint(pt, MONITOR_DEFAULTTONEAREST);
        var info = new MONITORINFO { cbSize = Marshal.SizeOf<MONITORINFO>() };
        GetMonitorInfo(mon, ref info);
        double scale = 1;
        if (GetDpiForMonitor(mon, 0, out var dpiX, out _) == 0)
            scale = dpiX / 96.0;
        return (info.rcMonitor, info.rcWork, scale);
    }

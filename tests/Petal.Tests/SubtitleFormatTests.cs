    [Fact]
    public void MicroDvd_reads_its_frame_rate_and_a_vobsub_is_refused()
    {
        var cues = Read(MicroDvd, F.MicroDvd);
        Assert.Equal(2, cues.Count);
        Assert.Equal((TimeSpan.FromSeconds(1), TimeSpan.FromSeconds(4)), (cues[0].Start, cues[0].End));
        Assert.Equal("Hello there\nGeneral Kenobi", cues[0].Text);
        Assert.Equal("<i>You are a bold one</i>", cues[1].Text);
        var vobsub = Encoding.Latin1.GetString([0x00, 0x00, 0x01, 0xBA, 0x44, 0x00, 0x04]);
        var error = Assert.Throws<InvalidDataException>(() => Read(vobsub, F.MicroDvd));
        Assert.Contains("VobSub", error.Message);
    }

    [Fact]
    public void Ttml_in_ticks_frames_offsets_and_with_italics()
    {
        var cues = Read(Streaming, F.Ttml);
        Assert.Equal(2, cues.Count);
        Assert.Equal(TimeSpan.FromSeconds(1.001), cues[0].Start);
        Assert.Equal(TimeSpan.FromSeconds(3.503), cues[0].End);
        Assert.Equal("مرحبًا\nكيف حالك؟", cues[0].Text);
        Assert.Equal((TimeSpan.FromSeconds(4), TimeSpan.FromSeconds(6)), (cues[1].Start, cues[1].End));
        Assert.Equal("<i>همس</i> بصوت منخفض", cues[1].Text);
        // The older namespace: frames at its rate, seconds and milliseconds, the div's begin added.
        var old = Read(OldDfxp, F.Ttml);
        Assert.Equal(TimeSpan.FromSeconds(11.5), old[0].Start);
        Assert.Equal(TimeSpan.FromSeconds(13), old[0].End);
        Assert.Equal((TimeSpan.FromSeconds(12), TimeSpan.FromSeconds(14.5)), (old[1].Start, old[1].End));
    }

    public static TheoryData<string, string> Pairs()
    {
        var data = new TheoryData<string, string>();
        foreach (var (from, to) in ConversionMatrix.AllPaths().Where(p => p.From.Family == FormatFamily.Subtitle && p.To.Family == FormatFamily.Subtitle))
            data.Add(from.Id, to.Id);
        return data;
    }

    [Theory]
    [MemberData(nameof(Pairs))]
    public async Task Every_format_to_every_other_keeps_the_words_and_their_times(string fromId, string toId)
    {
        var from = F.FromId(fromId)!;
        var to = F.FromId(toId)!;
        // Each format's own way of saying the same three cues.
        IReadOnlyList<SubtitleCue> sample =
        [
            new(TimeSpan.FromSeconds(1), TimeSpan.FromSeconds(3.5), "مرحبًا بكم"),
            new(TimeSpan.FromSeconds(4), TimeSpan.FromSeconds(6.2), "Two lines\nhere"),
            new(TimeSpan.FromSeconds(7), TimeSpan.FromSeconds(9), "<i>Whispered</i>"),
        ];
        var input = Path.Combine(_dir, $"{fromId}-{toId}.{from.WriteExtension}");
        await File.WriteAllTextAsync(input, SubtitleFile.Write(sample, from), new UTF8Encoding(false));
        var output = Path.Combine(_dir, $"{fromId}-{toId} out.{to.WriteExtension}");
        var converter = new SubtitleConverter();
        Assert.True(converter.CanConvert(from, to));
        await converter.ConvertAsync(new ConversionJob(input, from, to, output, ConversionSettings.Default), null, CancellationToken.None);

        var back = SubtitleFile.Read(SubtitleFile.Decode(await File.ReadAllBytesAsync(output)), to);
        Assert.Equal(3, back.Count);
        // MicroDVD counts frames, ASS and LRC hundredths: within one frame.
        var close = TimeSpan.FromMilliseconds(45);
        for (int i = 0; i < 3; i++)
        {
            Assert.InRange(back[i].Start, sample[i].Start - close, sample[i].Start + close);
            // LRC has no end of its own: a line ends where the next begins, or where an empty line says.
            if (to != F.Lrc && from != F.Lrc)
                Assert.InRange(back[i].End, sample[i].End - close, sample[i].End + close);
        }
        Assert.Equal("مرحبًا بكم", SubtitleFile.Plain(back[0].Text));
        // LRC holds one line a cue; the others keep the break.
        Assert.Equal(to == F.Lrc || from == F.Lrc ? "Two lines here" : "Two lines\nhere", SubtitleFile.Plain(back[1].Text));
        Assert.Equal("Whispered", SubtitleFile.Plain(back[2].Text));
    }

    [Fact]
    public void Translating_an_ass_file_changes_only_its_words()
    {
        var cues = Read(Aegisub, F.Ass);
        var translated = SubtitleFile.WithTexts(Aegisub, F.Ass, cues, ["طوكيو، 1999", "إلى أين نذهب بالضبط؟", "<i>مكان</i> هادئ.\nمع البحر."]);
        // Styles, the comment and the sign's position stay; the words are new, each in its own line's place.
        Assert.Contains("Style: Sign,Arial,50", translated);
        Assert.Contains("Comment: 0,0:00:06.00,0:00:07.00,Default,,0,0,0,,translator's note", translated);
        Assert.Contains("Dialogue: 0,0:00:01.00,0:00:03.50,Sign,,0,0,0,,{\\an8\\pos(960,80)}طوكيو، 1999", translated);
        Assert.Contains("Dialogue: 0,0:00:05.10,0:00:08.00,Default,Hana,0,0,0,,إلى أين نذهب بالضبط؟", translated);
        Assert.Contains("{\\i1}مكان{\\i0} هادئ.\\Nمع البحر.", translated);
        var again = Read(translated, F.Ass);
        Assert.Equal("طوكيو، 1999", again[0].Text);
    }

    [Fact]
    public async Task An_arabic_srt_in_windows_1256_reads_right()
    {
        var bytes = Encoding.GetEncoding(1256).GetBytes("1\r\n00:00:01,000 --> 00:00:02,000\r\nمرحبا بالعالم\r\n");
        var srt = Path.Combine(_dir, "old.srt");
        await File.WriteAllBytesAsync(srt, bytes);
        var vtt = Path.Combine(_dir, "old.vtt");
        // On an Arabic PC the code page is 1256; elsewhere this checks UTF-8 stays UTF-8 below.
        if (System.Globalization.CultureInfo.CurrentCulture.TextInfo.ANSICodePage == 1256)
        {
            await new SubtitleConverter().ConvertAsync(new ConversionJob(srt, F.Srt, F.Vtt, vtt, ConversionSettings.Default), null, CancellationToken.None);
            Assert.Contains("مرحبا بالعالم", await File.ReadAllTextAsync(vtt));
        }
        Assert.Equal("مرحبا", SubtitleFile.Decode(Encoding.UTF8.GetBytes("مرحبا")));
        Assert.Equal("مرحبا", SubtitleFile.Decode([0xEF, 0xBB, 0xBF, .. Encoding.UTF8.GetBytes("مرحبا")]));
    }


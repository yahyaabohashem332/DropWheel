    private static List<SubtitleCue> Read(string text, FileFormat format) => SubtitleFile.Read(text, format);

    [Fact]
    public void Ass_from_aegisub_in_time_order_with_lines_and_italics()
    {
        var cues = Read(Aegisub, F.Ass);
        Assert.Equal(3, cues.Count); // the comment and the drawing are not words
        Assert.Equal(("Tokyo, 1999", TimeSpan.FromSeconds(1), TimeSpan.FromSeconds(3.5)), (cues[0].Text, cues[0].Start, cues[0].End));
        Assert.Equal("Where are we going, exactly?", cues[1].Text);
        Assert.Equal("<i>Somewhere</i> quiet.\nWith the sea.", cues[2].Text);
        var old = Read(OldSsa, F.Ssa).Single();
        Assert.Equal("First line\nsecond", old.Text);
        Assert.Equal(TimeSpan.FromSeconds(2), old.Start);
    }

    [Fact]
    public void Lyrics_with_repeated_lines_offsets_and_word_times()
    {
        var cues = Read(Lyrics, F.Lrc);
        Assert.Equal(["The sun comes up", "And we sing along", "Over the hills", "And we sing along"], cues.Select(c => c.Text));
        // [offset:+500] shows every line half a second sooner.
        Assert.Equal(TimeSpan.FromSeconds(11.5), cues[0].Start);
        Assert.Equal(TimeSpan.FromSeconds(14.8), cues[0].End);
        // The empty [00:18.00] ends the line before it.
        Assert.Equal(TimeSpan.FromSeconds(17.5), cues[1].End);
        Assert.Equal(TimeSpan.FromSeconds(44.8), cues[3].Start);
    }

    [Fact]
    public void Sami_takes_the_language_with_most_lines_and_ends_at_blank_syncs()
